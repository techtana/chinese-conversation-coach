    private fun MutableMap<String, DictionaryEntry>.e(
        hanzi: String,
        pinyin: String,
        definition: String,
        hskLevel: Int = 0,
        pos: String = "",
        vararg examples: Pair<String, String>
    ) {
        put(hanzi, DictionaryEntry(hanzi, pinyin, definition, hskLevel, pos, examples.toList()))
    }

    fun lookup(word: String): DictionaryEntry? = entries[word]

    /**
     * Finds an entry whose English definition contains [english] as a full
     * sense (e.g. "tea" matches "tea", "to drink" matches "drink").
     */
    fun reverseLookup(english: String): DictionaryEntry? {
        val needle = english.trim().lowercase()
        if (needle.isBlank()) return null
        return entries.values.firstOrNull { entry ->
            entry.definition.lowercase().split(';', ',').any { sense ->
                val cleaned = sense.trim().removePrefix("to ").trim()
                cleaned == needle
            }
        }
    }

    fun lookupWithContext(hanzi: String, position: Int): DictionaryEntry? {
        // Try 4-char word
        if (position + 3 < hanzi.length) {
            entries[hanzi.substring(position, position + 4)]?.let { return it }
        }
        // Try 3-char word
        if (position + 2 < hanzi.length) {
            entries[hanzi.substring(position, position + 3)]?.let { return it }
        }
        // Try 2-char word starting here
        if (position + 1 < hanzi.length) {
            entries[hanzi.substring(position, position + 2)]?.let { return it }
        }
        // Try 2-char word ending here
        if (position > 0) {
            entries[hanzi.substring(position - 1, position + 1)]?.let { return it }
        }
        // Single character
        return entries[hanzi[position].toString()]
    }
